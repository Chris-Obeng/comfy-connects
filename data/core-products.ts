/**
 * The shop's own catalogue.
 *
 * The bags and the flagship gadgets are the line-up Comfy Connects posts on
 * TikTok (@comfyconnects): the WIWU Warriors bags, the LENYES shoulder bag,
 * the S2 Max smart glasses and the Phone Planet Hybrid Max. The rest of the
 * shelf is the same two brands' accessories — power banks, chargers, cables,
 * earbuds, stands and cases — which the shop orders alongside them.
 *
 * Every photo is the manufacturer's own studio shot, downloaded from wiwu.com
 * and lenyes.com into /public/products. Nothing hotlinks someone else's CDN.
 * Swap in the store's own photos when they shoot them.
 */

type Core = Omit<Product, "images" | "cutout" | "source"> & { shots: number };

